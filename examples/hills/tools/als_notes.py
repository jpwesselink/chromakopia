"""Turn an Ableton Live set's arrangement into note data for the hills demo.

    python3 examples/hills/tools/als_notes.py "orbital 3.als" > examples/hills/orbital3.rs

Reads every MIDI track's arrangement clips (loops played out, disabled
clips and notes skipped), its mixer volume and the set's tempo, and
writes them as Rust constants: the demo's synth plays them back itself,
so the song is a few kilobytes of notes, not audio. Meant for your own
sets — it parses the file with the standard library's XML parser.
"""

import gzip
import sys
from xml.etree.ElementTree import fromstring


def value(el, path, cast=float):
    e = el.find(path)
    return cast(e.get("Value")) if e is not None else None


def main(path):
    with gzip.open(path) as f:
        live = fromstring(f.read()).find("LiveSet")
    bpm = value(live, ".//MasterTrack//Tempo/Manual")
    tracks, notes, end_beat = [], [], 0.0
    for tr in live.find("Tracks"):
        if tr.tag != "MidiTrack":
            continue
        index = len(tracks)
        name = tr.find("Name/EffectiveName").get("Value")
        volume = value(tr, "DeviceChain/Mixer/Volume/Manual")
        tracks.append((name, volume))
        events = tr.find(".//ArrangerAutomation/Events")
        for clip in events.findall("MidiClip") if events is not None else []:
            if value(clip, "Disabled", str) == "true":
                continue
            start, end = value(clip, "CurrentStart"), value(clip, "CurrentEnd")
            loop = clip.find("Loop")
            loop_start, loop_end = value(loop, "LoopStart"), value(loop, "LoopEnd")
            looping = value(loop, "LoopOn", str) == "true"
            content = [
                (float(n.get("Time")), float(n.get("Duration")), value(kt, "MidiKey", int), float(n.get("Velocity")))
                for kt in clip.findall(".//KeyTracks/KeyTrack")
                for n in kt.findall("Notes/MidiNoteEvent")
                if n.get("IsEnabled", "true") != "false"
            ]
            # Play the clip's content out along its stretch of the arrangement.
            pos = loop_start + (value(loop, "StartRelative") if looping else 0.0)
            t = start
            while t < end - 1e-9:
                stop = loop_end if looping else float("inf")
                for at, length, key, velocity in content:
                    if pos <= at < stop and t + at - pos < end - 1e-9:
                        on = t + at - pos
                        notes.append((on, min(length, end - on), index, key, round(velocity)))
                if not looping:
                    break
                t += stop - pos
                pos = loop_start
            end_beat = max(end_beat, end)
    notes.sort()

    out = [
        f"//! Generated by tools/als_notes.py from {path.split('/')[-1]!r} — do not edit.",
        "",
        "use super::music::Note;",
        "",
        f"pub const BPM: f64 = {bpm!r};",
        f"/// Beats until the song starts over.",
        f"pub const BEATS: f64 = {end_beat!r};",
        "/// (track name, mixer volume) per track, in track order.",
        f"pub const TRACKS: [(&str, f32); {len(tracks)}] = [",
        *[f"    ({name!r}, {volume!r})," .replace("'", '"') for name, volume in tracks],
        "];",
        f"pub const NOTES: [Note; {len(notes)}] = [",
    ]
    for on, length, track, key, velocity in notes:
        out.append(f"    Note {{ at: {on!r}, len: {length!r}, track: {track}, key: {key}, vel: {velocity} }},")
    out.append("];")
    print("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1])
