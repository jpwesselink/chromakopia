"""Turn an Ableton Live set's Session View into loops for the hills demo.

    python3 examples/hills/tools/als_notes.py "orbital 3.als" > examples/hills/orbital3.rs

Reads every MIDI track's session clips — its loops, in slot order: name,
loop length, and the notes inside the loop, timed from the loop's start —
plus each track's name and mixer volume and the set's tempo, and writes
them as Rust constants. The scroll text launches the loops (`{play …}`),
and the demo's synth plays them itself: the song is a few kilobytes of
notes, not audio. Empty and disabled clips are left out. Meant for your
own sets — it parses the file with the standard library's XML parser.
"""

import gzip
import sys
from xml.etree.ElementTree import fromstring


def value(el, path, cast=float):
    e = el.find(path)
    return cast(e.get("Value")) if e is not None else None


def main(path):
    with gzip.open(path) as f:
        live = fromstring(f.read()).find("LiveSet")
    bpm = value(live, ".//MasterTrack//Tempo/Manual")
    tracks, clips = [], []
    for tr in live.find("Tracks"):
        if tr.tag != "MidiTrack":
            continue
        index = len(tracks)
        name = tr.find("Name/EffectiveName").get("Value")
        tracks.append((name, value(tr, "DeviceChain/Mixer/Volume/Manual")))
        for slot in tr.findall(".//MainSequencer/ClipSlotList/ClipSlot"):
            clip = slot.find(".//MidiClip")
            if clip is None or value(clip, "Disabled", str) == "true":
                continue
            loop = clip.find("Loop")
            start, end = value(loop, "LoopStart"), value(loop, "LoopEnd")
            notes = sorted(
                (float(n.get("Time")) - start, float(n.get("Duration")), value(kt, "MidiKey", int), round(float(n.get("Velocity"))))
                for kt in clip.findall(".//KeyTracks/KeyTrack")
                for n in kt.findall("Notes/MidiNoteEvent")
                if n.get("IsEnabled", "true") != "false" and start <= float(n.get("Time")) < end
            )
            if notes:
                clips.append((index, clip.find("Name").get("Value"), end - start, notes))

    def rust(s):
        return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

    out = [
        f"//! Generated by tools/als_notes.py from {path.split('/')[-1]!r} — do not edit.",
        "",
        "use super::music::{Clip, Note};",
        "",
        f"pub const BPM: f64 = {bpm!r};",
        "/// (track name, mixer volume) per track, in track order.",
        "#[cfg_attr(not(test), allow(dead_code))]",
        f"pub const TRACKS: [(&str, f32); {len(tracks)}] = [",
        *[f"    ({rust(name)}, {volume!r})," for name, volume in tracks],
        "];",
        "/// The Session View's loops, track by track, in slot order.",
        f"pub const CLIPS: [Clip; {len(clips)}] = [",
    ]
    for track, name, beats, notes in clips:
        out.append(f"    Clip {{ track: {track}, name: {rust(name)}, beats: {beats!r}, notes: &[")
        for at, length, key, velocity in notes:
            out.append(f"        Note {{ at: {at!r}, len: {length!r}, track: {track}, key: {key}, vel: {velocity} }},")
        out.append("    ] },")
    out.append("];")
    print("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1])
